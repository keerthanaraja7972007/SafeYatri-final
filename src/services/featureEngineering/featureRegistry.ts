/**
 * Build the feature availability matrix from the registry.
 * Availability is determined by checking which source datasets have records.
 */
export function buildAvailabilityMatrix(
  datasetRecordCounts: Record<string, number>
): FeatureAvailabilityEntry[] {
  return FEATURE_REGISTRY.map((def) => {
    const sourceCount = datasetRecordCounts[def.source_dataset] ?? 0;
    let available: boolean;

    if (def.source_dataset === 'tourist_places') {
      available = sourceCount > 0;
    } else if (def.is_derived && def.source_fields[0] === 'recorded_at') {
      // Temporal features derived from weather timestamps
      available = (datasetRecordCounts['weather_data'] ?? 0) > 0;
    } else if (def.feature_name === 'season_indicator') {
      available = (datasetRecordCounts['tourism_context'] ?? 0) > 0;
    } else {
      available = sourceCount > 0;
    }

    return {
      feature_name: def.feature_name,
      display_name: def.display_name,
      source: def.source_dataset,
      available,
      type: def.data_type,
      category: def.category,
    };
  });
}

export function getFeaturesByCategory(category: string): FeatureDefinition[] {
  return FEATURE_REGISTRY.filter((f) => f.category === category);
}

export function getFeatureByName(name: string): FeatureDefinition | undefined {
  return FEATURE_REGISTRY.find((f) => f.feature_name === name);
}
